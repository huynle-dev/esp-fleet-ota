#!/usr/bin/env python3
"""Generate the TEST-ONLY signature vectors used by the native tests (test/fixtures/fota_test_vectors.h).

The keys made here are throwaway P-256 keys for unit tests. They are committed ONLY as test fixtures, are named
TEST_ONLY_*, and must never be added to a device's trusted key list. Re-running this script makes new keys and new
signatures (ECDSA is randomized), which is fine: the tests only need self-consistent vectors.

    python3 tools/gen_test_vectors.py

writes test/fixtures/fota_test_vectors.h AND examples/minimal/src/test_only_keys.h from the same keys, so the example
can never drift from the fixtures (test/test_example_keys checks it).
"""
import base64
import json
import os
import sys

from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fota_release  # noqa: E402  the manifest bytes come from the release tool's encoder (cross-check)

SHA = "9f86d081884c7d659a2feaa0c55ad015a3bf4f1b2b0b822cd15d6c15b0f00a08"   # sha256("test")
MANIFEST = (
    '{"schema":1,"product":"demo-device","chip":"esp32c3","channel":"stable","version":"1.1.0",'
    '"min_version":"1.0.0","url":"https://fw.example.com/demo-device/1.1.0/esp32c3/firmware.bin","size":4,'
    '"sha256":"' + SHA + '","key_id":"test-only-esp-fleet-ota","released_at":"2026-11-22T10:00:00Z"}'
)
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FIXTURE = os.path.join(ROOT, "test", "fixtures", "fota_test_vectors.h")
EXAMPLE = os.path.join(ROOT, "examples", "minimal", "src", "test_only_keys.h")
OPENBAO_ID = "test-only-esp-fleet-ota"              # stands in for the real "esp-fleet-ota"
BREAKGLASS_ID = "test-only-esp-fleet-ota-breakglass"  # stands in for your break-glass key id


# A factory descriptor (browser flashing). Not an OTA manifest: the device parser must refuse it (test_manifest).
FACTORY = fota_release.encode_factory({
    "schema": 1, "product": "demo-device", "chip": "esp32c3", "version": "1.1.0",
    "factory_url": "https://fw.example.com/demo-device/1.1.0/esp32c3/factory.bin", "factory_sha256": SHA,
    "factory_size": 4, "key_id": "test-only-esp-fleet-ota", "released_at": "2026-11-22T10:00:00Z"}).decode()

# The release tool must produce exactly these bytes, so the C++ tests also cover tool-made manifests.
assert fota_release.encode_manifest(json.loads(MANIFEST)) == MANIFEST.encode(), "tool encoder drifted"


def pem_pub(key):
    return key.public_key().public_bytes(serialization.Encoding.PEM,
                                         serialization.PublicFormat.SubjectPublicKeyInfo).decode()


def der_pub(key):
    return key.public_key().public_bytes(serialization.Encoding.DER,
                                         serialization.PublicFormat.SubjectPublicKeyInfo)


def c_str(s):
    out = []
    for line in s.splitlines(keepends=True):
        out.append('"' + line.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"')
    return "\n    ".join(out) if out else '""'


def c_bytes(b):
    return ", ".join(f"0x{x:02x}" for x in b)


def main():
    a = ec.generate_private_key(ec.SECP256R1())
    b = ec.generate_private_key(ec.SECP256R1())
    p384 = ec.generate_private_key(ec.SECP384R1())
    msg = MANIFEST.encode()
    sig_a = a.sign(msg, ec.ECDSA(hashes.SHA256()))
    sig_b = b.sign(msg, ec.ECDSA(hashes.SHA256()))
    sig_a_b64 = base64.b64encode(sig_a).decode()
    der_a = der_pub(a)
    out = []
    w = out.append
    w("// GENERATED by tools/gen_test_vectors.py. TEST-ONLY keys and signatures: never trust these on a device.\n")
    w("#pragma once\n#include <cstddef>\n#include <cstdint>\n\n")
    w(f"static const char TEST_ONLY_MANIFEST[] =\n    {c_str(MANIFEST)};\n\n")
    w(f"static const char TEST_ONLY_FACTORY[] =\n    {c_str(FACTORY)};\n\n")
    w(f"static const char TEST_ONLY_KEY_A_PEM[] =\n    {c_str(pem_pub(a))};\n\n")
    w(f"static const uint8_t TEST_ONLY_KEY_A_DER[] = {{{c_bytes(der_a)}}};\n\n")
    w(f"static const char TEST_ONLY_KEY_B_PEM[] =\n    {c_str(pem_pub(b))};\n\n")
    w(f"static const char TEST_ONLY_KEY_P384_PEM[] =\n    {c_str(pem_pub(p384))};\n\n")
    w(f'static const char TEST_ONLY_SIG_A_B64[] = "{sig_a_b64}";\n')
    w(f'static const char TEST_ONLY_SIG_A_VAULT_V1[] = "vault:v1:{sig_a_b64}";\n')
    w(f'static const char TEST_ONLY_SIG_A_VAULT_V2[] = "vault:v2:{sig_a_b64}";\n')
    sig_b_b64 = base64.b64encode(sig_b).decode()
    w(f'static const char TEST_ONLY_SIG_B_B64[] = "{sig_b_b64}";\n')
    w(f'static const char TEST_ONLY_SIG_B_VAULT_V2[] = "vault:v2:{sig_b_b64}";\n')
    with open(FIXTURE, "w") as f:
        f.write("".join(out))
    ex = ["// GENERATED by tools/gen_test_vectors.py from the same keys as test/fixtures/fota_test_vectors.h.\n",
          "// TEST-ONLY keys and ids for examples/minimal: a real device uses the key ids and public keys you configure\n",
          "// for your signing service (docs/integration.md), which must match exactly.\n#pragma once\n\n",
          f'static const char kExampleTestOnlyOpenBaoKeyId[] = "{OPENBAO_ID}";       // OpenBao transit, N = 1\n',
          f'static const char kExampleTestOnlyBreakGlassKeyId[] = "{BREAKGLASS_ID}";  // bare signatures, N = 0\n\n',
          f"static const char kExampleTestOnlyOpenBaoPem[] =\n    {c_str(pem_pub(a))};\n\n",
          f"static const char kExampleTestOnlyBreakGlassPem[] =\n    {c_str(pem_pub(b))};\n"]
    with open(EXAMPLE, "w") as f:
        f.write("".join(ex))
    print("wrote", os.path.relpath(FIXTURE, ROOT), "and", os.path.relpath(EXAMPLE, ROOT))


if __name__ == "__main__":
    main()
